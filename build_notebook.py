# ── CELL 4 ───────────────────────────────────────────────────────────────────
cells.append(code_cell(
    "# ============================================================\n"
    "# HELPER FUNCTIONS\n"
    "# ============================================================\n"
    "\n"
    "def get_predictions(model, dataset, batch_size=512):\n"
    "    \"\"\"Returns (X, Y_true, Y_pred, gates, embeddings) as numpy arrays.\"\"\"\n"
    "    model.eval()\n"
    "    Xs, Ys, Yhats, Gs, Es = [], [], [], [], []\n"
    "    with torch.no_grad():\n"
    "        for x, y in DataLoader(dataset, batch_size=batch_size, shuffle=False):\n"
    "            g  = model.gating_net.get_gates(x)\n"
    "            e  = model.encdec.encoder(x * g)\n"
    "            yh = model.clustering_head(e).argmax(dim=-1)\n"
    "            Xs.append(x.numpy()); Ys.append(y.numpy())\n"
    "            Yhats.append(yh.numpy()); Gs.append(g.numpy()); Es.append(e.numpy())\n"
    "    return (np.concatenate(Xs), np.concatenate(Ys),\n"
    "            np.concatenate(Yhats), np.concatenate(Gs), np.concatenate(Es))\n"
    "\n"
    "\n"
    "def clustering_metrics(Y_true, Y_pred, n_cl):\n"
    "    \"\"\"Returns (ACC, ARI, NMI).\"\"\"\n"
    "    return (get_accuracy(Y_pred, Y_true, n_cl),\n"
    "            adjusted_rand_score(Y_true, Y_pred),\n"
    "            normalized_mutual_info_score(Y_true, Y_pred))\n"
    "\n"
    "\n"
    "def binarize_topk(gates, k):\n"
    "    \"\"\"Per-sample: keep top-k gate positions as 1, rest 0.\"\"\"\n"
    "    out = np.zeros_like(gates)\n"
    "    for i in range(len(gates)):\n"
    "        out[i, np.argsort(-gates[i])[:k]] = 1.0\n"
    "    return out\n"
    "\n"
    "\n"
    "def compute_all_interp_metrics(model, X, Y_pred, Y_true, n_cl, k=15, sub=2000, sub_u=500):\n"
    "    \"\"\"Compute all 4 interpretability metrics using top-k gates (|S|=k).\"\"\"\n"
    "    X_t = torch.tensor(X, dtype=torch.float32)\n"
    "    with torch.no_grad():\n"
    "        gates_cont = model.gating_net.get_gates(X_t).numpy()\n"
    "    G = binarize_topk(gates_cont, k)\n"
    "\n"
    "    def infer(x_in):\n"
    "        xt = torch.tensor(x_in, dtype=torch.float32)\n"
    "        with torch.no_grad():\n"
    "            g = model.gating_net.get_gates(xt)\n"
    "            return model.clustering_head(model.encdec.encoder(xt * g)).argmax(-1).numpy()\n"
    "\n"
    "    div_   = diversity(Y_pred, G, n_cl, X.shape[1])\n"
    "    faith_ = faithfulness(G[:sub], X[:sub], infer, Y_true[:sub], X.shape[1])\n"
    "    uniq_  = uniqueness(X[:sub_u], G[:sub_u], k=2, subset_size=sub_u)\n"
    "\n"
    "    from sklearn.model_selection import train_test_split\n"
    "    X_tr, X_te, g_tr, g_te, y_tr, y_te = train_test_split(\n"
    "        X, G, Y_true, test_size=0.2, random_state=42, stratify=Y_true)\n"
    "    gen_ = generalizability(X_tr, g_tr, y_tr, X_te, g_te, y_te) * 100\n"
    "    return div_, faith_, uniq_, gen_\n"
    "\n"
    "\n"
    "def make_trainer_cfg(max_epochs=200):\n"
    "    return OmegaConf.create({\n"
    "        'devices': 1, 'accelerator': DEVICE, 'max_epochs': max_epochs,\n"
    "        'deterministic': True, 'logger': True, 'log_every_n_steps': 10,\n"
    "        'check_val_every_n_epoch': 10, 'enable_checkpointing': False,\n"
    "        'num_sanity_val_steps': 0\n"
    "    })\n"
    "\n"
    "\n"
    "def train_idc(cfg, seed=0, log_dir='results', module_cls=None, verbose=True):\n"
    "    \"\"\"Train IDC (or a subclass) and return the trained model.\"\"\"\n"
    "    if module_cls is None:\n"
    "        module_cls = BaseModule\n"
    "    cfg.seed = seed\n"
    "    seed_everything(seed, workers=True)\n"
    "    np.random.seed(seed)\n"
    "    os.makedirs(log_dir, exist_ok=True)\n"
    "    model = module_cls(cfg)\n"
    "    logger = TensorBoardLogger(log_dir, name=cfg.dataset, log_graph=False)\n"
    "    trainer = Trainer(\n"
    "        **cfg.trainer,\n"
    "        callbacks=[LearningRateMonitor(logging_interval='step')],\n"
    "        enable_model_summary=verbose, enable_progress_bar=verbose\n"
    "    )\n"
    "    trainer.logger = logger\n"
    "    trainer.fit(model)\n"
    "    return model\n"
    "\n"
    "\n"
    "print('Helper functions ready.')"
))

