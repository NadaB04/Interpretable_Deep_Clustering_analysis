    "class _NoReg(_BM):\n"
    "    \"\"\"Remove Lreg: zero out the sparsity regularisation term in ae_step.\"\"\"\n"
    "    def ae_step(self, x):\n"
    "        if self.current_epoch > self.cfg.ae_non_gated_epochs:\n"
    "            mu, _, gates = self.gating_net(x)\n"
    "            gtcr_loss = self.gtcr_loss(gates) / x.size(0)\n"
    "            loss = gtcr_loss * self.cfg.gtcr_lambda  # no reg_loss term\n"
    "        else:\n"
    "            gates = torch.ones_like(x)\n"
    "            loss  = 0\n"
    "        recon_g = self.encdec(x * gates) if not isinstance(loss, int) else self.encdec(x)\n"
