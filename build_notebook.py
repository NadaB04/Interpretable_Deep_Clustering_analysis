    "\n"
    "        # Top-100 highest-variance features for tractability\n"
    "        top100 = np.argsort(-X_al.var(axis=0))[:100]\n"
    "        X_sub  = X_al[:, top100]\n"
    "        from sklearn.preprocessing import MinMaxScaler as _MMS\n"
    "        X_norm = _MMS((-0.499, 0.499)).fit_transform(X_sub)\n"
